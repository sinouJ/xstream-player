import SwiftUI

// Alias de compatibilité — toutes les valeurs vivent dans AppTheme.Colors.
enum LoginTheme {
    static let background  = AppTheme.Colors.background
    static let fieldBg     = AppTheme.Colors.surface
    static let fieldBorder = AppTheme.Colors.border
    static let accent      = AppTheme.Colors.accent
    static let label       = AppTheme.Colors.label
    static let muted       = AppTheme.Colors.accentSubtle
    static let buttonStart = AppTheme.Colors.gradientStart
    static let buttonEnd   = AppTheme.Colors.gradientEnd
}
